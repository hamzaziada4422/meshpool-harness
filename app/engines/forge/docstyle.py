"""Word documents that read as written in Word (make_document, meshpool_harness/agent/office_mcp_server.py).

Daniel, 0.0.19: the memo used style "Normal" for every paragraph (no Heading styles, so no navigation pane or table of
contents), bullets were typed "•" characters, the table had no cell padding and File > Info said "generated by
python-docx". Here: Heading 1 and 2 for headings (a line that is only a bold label is a Heading 2), the List Bullet
style for bullets, table cells with padding, the brand's heading face and colour, the footer on every page, and core
properties with the document's title and the user's name.
"""
from __future__ import annotations

import re

HEX = re.compile(r"^#?([0-9A-Fa-f]{6})$")


def style(doc, heading_font: str | None = None, font: str | None = None, color: str | None = None) -> None:
    from docx.oxml.ns import qn
    from docx.shared import Pt, RGBColor

    def face(st, name):
        st.font.name = name
        rpr = st.element.get_or_add_rPr()
        fonts = rpr.find(qn("w:rFonts"))
        if fonts is None:
            fonts = rpr.makeelement(qn("w:rFonts"), {})
            rpr.append(fonts)
        for k in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
            fonts.set(qn(k), name)
        for k in ("w:asciiTheme", "w:hAnsiTheme", "w:cstheme", "w:eastAsiaTheme"):
            fonts.attrib.pop(qn(k), None)

    if font:
        face(doc.styles["Normal"], font)
    c = HEX.match(str(color or "").strip())
    for name, size in (("Title", 22), ("Heading 1", 15), ("Heading 2", 12.5), ("Heading 3", 11.5)):
        try:
            st = doc.styles[name]
        except KeyError:
            continue
        if heading_font or font:
            face(st, heading_font or font)
        if c:
            st.font.color.rgb = RGBColor.from_string(c.group(1).upper())
        st.font.size = Pt(size)
        pf = st.paragraph_format
        pf.space_before = Pt(10 if name != "Title" else 0)
        pf.space_after = Pt(4)
        pf.keep_with_next = True


def bold_heading(line: str) -> str | None:
    """'**Recommendation**' or '**Next steps:**' alone on its line: the heading it stands for."""
    m = re.fullmatch(r"\*\*([^*]{2,80}?)\*\*\s*:?", line.strip())
    if m and len(m.group(1).split()) <= 8:
        return m.group(1).strip().rstrip(":")
    return None


def first_heading(md: str) -> str | None:
    for ln in (md or "").splitlines():
        m = re.match(r"^\s*#{1,3}\s+(.+)", ln)
        if m:
            return re.sub(r"\*\*", "", m.group(1)).strip()
    return None


def table(t, top_bottom_twips: int = 60, sides_twips: int = 110) -> None:
    """Padding inside every cell (Word's default grid has none above and below the text), header row repeated."""
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    tblPr = t._tbl.tblPr
    old = tblPr.find(qn("w:tblCellMar"))
    if old is not None:
        tblPr.remove(old)
    mar = OxmlElement("w:tblCellMar")
    for side, v in (("top", top_bottom_twips), ("left", sides_twips), ("bottom", top_bottom_twips),
                    ("right", sides_twips)):
        el = OxmlElement(f"w:{side}")
        el.set(qn("w:w"), str(v))
        el.set(qn("w:type"), "dxa")
        mar.append(el)
    tblPr.append(mar)
    try:
        trPr = t.rows[0]._tr.get_or_add_trPr()
        h = OxmlElement("w:tblHeader")
        h.set(qn("w:val"), "true")
        trPr.append(h)
    except Exception:  # noqa: BLE001
        pass


def finish(doc, title: str | None = None, footer: str | None = None, author: str | None = None) -> None:
    from .docmeta import set_core
    set_core(doc.core_properties, title=title, who=author)
    if footer:
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        for sec in doc.sections:
            p = sec.footer.paragraphs[0] if sec.footer.paragraphs else sec.footer.add_paragraph()
            p.text = footer
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
