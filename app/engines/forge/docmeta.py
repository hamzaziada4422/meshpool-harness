"""Document properties of the files the engines make (File > Info in Office).

Daniel, 0.0.19: the memo's core properties said "generated by python-docx"; the decks said "generated using
python-pptx", last modified by "Steve Canny" in 2013 (python-pptx's own template). A client sees these. The author is
the user's name from Settings > Profile (else left blank), the title is the document's own title, and no library
name is ever written.
"""
from __future__ import annotations

import datetime as _dt
import re

LIBS = re.compile(r"(?i)python-docx|python-pptx|openpyxl|xlsxwriter|generated (?:using|by)|steve canny")


def author() -> str:
    """The user's name from their profile, or "" (never a library or product name)."""
    try:
        from meshpool_harness.ui import settings_v2 as SV
        return (SV.profile().get("name") or "").strip()
    except Exception:  # noqa: BLE001 - installed without the app: no profile
        return ""


def _now():
    return _dt.datetime.now(_dt.timezone.utc).replace(tzinfo=None, microsecond=0)


def set_core(cp, title: str | None = None, who: str | None = None) -> None:
    """python-docx / python-pptx core properties: title, author, no library text, fresh dates."""
    who = author() if who is None else who
    if title:
        cp.title = re.sub(r"\s+", " ", re.sub(r"\*\*|\^\w+", "", str(title))).strip()[:250]
    cp.author = who
    cp.last_modified_by = who
    for k in ("comments", "keywords", "subject", "category"):
        try:
            if LIBS.search(getattr(cp, k) or "") or k == "comments":
                setattr(cp, k, "")
        except (AttributeError, ValueError):
            pass
    try:
        cp.created = cp.modified = _now()
        cp.revision = 1
    except (AttributeError, ValueError):
        pass


def set_workbook(wb, title: str | None = None, who: str | None = None) -> None:
    """openpyxl's properties: creator "openpyxl" becomes the user (or blank)."""
    who = author() if who is None else who
    p = wb.properties
    p.creator = who
    p.lastModifiedBy = who
    if title:
        p.title = str(title)[:250]
    for k in ("description", "keywords", "subject", "category"):
        if LIBS.search(str(getattr(p, k, "") or "")):
            setattr(p, k, None)
    p.created = p.modified = _now()
